-- HBOPAMS: Oracle 21c XE schema foundation
-- Run as the dedicated application schema user.
-- This script is intentionally idempotent only on a new schema.

CREATE TABLE departments (
    department_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name     VARCHAR2(100) NOT NULL,
    alert_threshold_pct NUMBER(5,2) DEFAULT 85 NOT NULL,
    CONSTRAINT uq_department_name UNIQUE (department_name),
    CONSTRAINT ck_dept_threshold CHECK (alert_threshold_pct BETWEEN 1 AND 100)
);

CREATE TABLE patients (
    patient_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_number VARCHAR2(30) NOT NULL,
    first_name      VARCHAR2(80) NOT NULL,
    last_name       VARCHAR2(80) NOT NULL,
    date_of_birth   DATE,
    sex             VARCHAR2(20),
    phone_number    VARCHAR2(30),
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_patient_hospital_number UNIQUE (hospital_number),
    CONSTRAINT ck_patient_sex CHECK (sex IN ('FEMALE', 'MALE', 'OTHER', 'UNKNOWN'))
);

CREATE TABLE staff (
    staff_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id   NUMBER,
    employee_number VARCHAR2(30) NOT NULL,
    first_name      VARCHAR2(80) NOT NULL,
    last_name       VARCHAR2(80) NOT NULL,
    staff_role      VARCHAR2(30) NOT NULL,
    active_flag     CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT uq_staff_employee_number UNIQUE (employee_number),
    CONSTRAINT fk_staff_department FOREIGN KEY (department_id)
        REFERENCES departments(department_id),
    CONSTRAINT ck_staff_role CHECK (staff_role IN ('RECEPTIONIST', 'NURSE', 'DOCTOR', 'ADMINISTRATOR')),
    CONSTRAINT ck_staff_active CHECK (active_flag IN ('Y', 'N'))
);

-- An application account is separate from a staff record. This lets the PL/SQL
-- layer block inactive accounts even when a caller connects directly in SQL Developer.
CREATE TABLE app_users (
    user_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_id         NUMBER NOT NULL,
    username         VARCHAR2(60) NOT NULL,
    active_flag      CHAR(1) DEFAULT 'Y' NOT NULL,
    created_at       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_app_user_staff UNIQUE (staff_id),
    CONSTRAINT uq_app_user_username UNIQUE (username),
    CONSTRAINT fk_app_user_staff FOREIGN KEY (staff_id) REFERENCES staff(staff_id),
    CONSTRAINT ck_app_user_active CHECK (active_flag IN ('Y', 'N'))
);

CREATE TABLE user_roles (
    user_role_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          NUMBER NOT NULL,
    role_name        VARCHAR2(30) NOT NULL,
    assigned_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    assigned_by_id   NUMBER,
    CONSTRAINT uq_user_role UNIQUE (user_id, role_name),
    CONSTRAINT fk_user_role_user FOREIGN KEY (user_id) REFERENCES app_users(user_id),
    CONSTRAINT fk_user_role_assigner FOREIGN KEY (assigned_by_id) REFERENCES app_users(user_id),
    CONSTRAINT ck_user_role_name CHECK (role_name IN ('RECEPTIONIST', 'NURSE', 'DOCTOR', 'ADMINISTRATOR'))
);

CREATE TABLE rooms (
    room_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id   NUMBER NOT NULL,
    room_number     VARCHAR2(20) NOT NULL,
    room_type       VARCHAR2(30) DEFAULT 'GENERAL' NOT NULL,
    CONSTRAINT uq_room_department_number UNIQUE (department_id, room_number),
    CONSTRAINT fk_room_department FOREIGN KEY (department_id)
        REFERENCES departments(department_id),
    CONSTRAINT ck_room_type CHECK (room_type IN ('GENERAL', 'PRIVATE', 'ICU', 'ISOLATION'))
);

CREATE TABLE beds (
    bed_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id          NUMBER NOT NULL,
    bed_code         VARCHAR2(30) NOT NULL,
    bed_status       VARCHAR2(20) DEFAULT 'AVAILABLE' NOT NULL,
    last_status_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_bed_code UNIQUE (bed_code),
    CONSTRAINT fk_bed_room FOREIGN KEY (room_id) REFERENCES rooms(room_id),
    CONSTRAINT ck_bed_status CHECK (bed_status IN ('AVAILABLE', 'OCCUPIED', 'CLEANING', 'MAINTENANCE'))
);

CREATE TABLE admissions (
    admission_id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id               NUMBER NOT NULL,
    department_id            NUMBER NOT NULL,
    bed_id                   NUMBER,
    admitted_by_staff_id     NUMBER,
    admitted_at              TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    expected_discharge_date  DATE,
    discharged_at            TIMESTAMP,
    discharge_recorded_by_id NUMBER,
    admission_status         VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    notes                    VARCHAR2(1000),
    CONSTRAINT fk_admission_patient FOREIGN KEY (patient_id) REFERENCES patients(patient_id),
    CONSTRAINT fk_admission_department FOREIGN KEY (department_id) REFERENCES departments(department_id),
    CONSTRAINT fk_admission_bed FOREIGN KEY (bed_id) REFERENCES beds(bed_id),
    CONSTRAINT fk_admitted_by FOREIGN KEY (admitted_by_staff_id) REFERENCES staff(staff_id),
    CONSTRAINT fk_discharged_by FOREIGN KEY (discharge_recorded_by_id) REFERENCES staff(staff_id),
    CONSTRAINT ck_admission_status CHECK (admission_status IN ('PENDING', 'ADMITTED', 'DISCHARGED', 'CANCELLED')),
    CONSTRAINT ck_discharge_after_admission CHECK (discharged_at IS NULL OR discharged_at >= admitted_at)
);

CREATE TABLE admission_requests (
    request_id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id              NUMBER NOT NULL,
    department_id           NUMBER NOT NULL,
    requested_by_user_id    NUMBER NOT NULL,
    requested_at            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    priority_level          VARCHAR2(15) DEFAULT 'ROUTINE' NOT NULL,
    request_status          VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    reviewed_by_user_id     NUMBER,
    reviewed_at             TIMESTAMP,
    review_note             VARCHAR2(500),
    CONSTRAINT fk_request_patient FOREIGN KEY (patient_id) REFERENCES patients(patient_id),
    CONSTRAINT fk_request_department FOREIGN KEY (department_id) REFERENCES departments(department_id),
    CONSTRAINT fk_request_requester FOREIGN KEY (requested_by_user_id) REFERENCES app_users(user_id),
    CONSTRAINT fk_request_reviewer FOREIGN KEY (reviewed_by_user_id) REFERENCES app_users(user_id),
    CONSTRAINT ck_request_priority CHECK (priority_level IN ('ROUTINE', 'URGENT', 'EMERGENCY')),
    CONSTRAINT ck_request_status CHECK (request_status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED'))
);

CREATE TABLE bed_status_history (
    bed_status_history_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bed_id                NUMBER NOT NULL,
    old_status            VARCHAR2(20),
    new_status            VARCHAR2(20) NOT NULL,
    changed_at            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    changed_by_staff_id   NUMBER,
    change_reason         VARCHAR2(300),
    CONSTRAINT fk_bed_history_bed FOREIGN KEY (bed_id) REFERENCES beds(bed_id),
    CONSTRAINT fk_bed_history_staff FOREIGN KEY (changed_by_staff_id) REFERENCES staff(staff_id),
    CONSTRAINT ck_history_old_status CHECK (old_status IS NULL OR old_status IN ('AVAILABLE', 'OCCUPIED', 'CLEANING', 'MAINTENANCE')),
    CONSTRAINT ck_history_new_status CHECK (new_status IN ('AVAILABLE', 'OCCUPIED', 'CLEANING', 'MAINTENANCE'))
);

CREATE TABLE audit_log (
    audit_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_name     VARCHAR2(50) NOT NULL,
    entity_id       NUMBER NOT NULL,
    action_name     VARCHAR2(30) NOT NULL,
    action_at       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    db_user         VARCHAR2(128) DEFAULT USER NOT NULL,
    details         VARCHAR2(1000)
);

CREATE TABLE capacity_alerts (
    alert_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id     NUMBER NOT NULL,
    alert_type        VARCHAR2(30) NOT NULL,
    occupancy_pct     NUMBER(5,2),
    alert_status      VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
    created_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    resolved_at       TIMESTAMP,
    resolved_by_id    NUMBER,
    alert_message     VARCHAR2(500) NOT NULL,
    CONSTRAINT fk_alert_department FOREIGN KEY (department_id) REFERENCES departments(department_id),
    CONSTRAINT fk_alert_resolver FOREIGN KEY (resolved_by_id) REFERENCES app_users(user_id),
    CONSTRAINT ck_alert_type CHECK (alert_type IN ('HIGH_OCCUPANCY', 'NO_AVAILABLE_BEDS', 'FORECAST_CAPACITY')),
    CONSTRAINT ck_alert_status CHECK (alert_status IN ('OPEN', 'RESOLVED'))
);

CREATE TABLE data_load_runs (
    load_run_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_name       VARCHAR2(200) NOT NULL,
    source_url        VARCHAR2(1000) NOT NULL,
    started_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    completed_at      TIMESTAMP,
    source_row_count  NUMBER DEFAULT 0 NOT NULL,
    loaded_row_count  NUMBER DEFAULT 0 NOT NULL,
    rejected_row_count NUMBER DEFAULT 0 NOT NULL,
    load_status       VARCHAR2(20) DEFAULT 'RUNNING' NOT NULL,
    CONSTRAINT ck_load_status CHECK (load_status IN ('RUNNING', 'COMPLETED', 'FAILED'))
);

CREATE TABLE rejected_data_rows (
    rejected_row_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    load_run_id       NUMBER NOT NULL,
    source_row_number NUMBER,
    raw_record        CLOB NOT NULL,
    rejection_reason  VARCHAR2(1000) NOT NULL,
    rejected_at       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_rejected_load FOREIGN KEY (load_run_id) REFERENCES data_load_runs(load_run_id)
);

CREATE INDEX ix_admissions_patient ON admissions(patient_id);
CREATE INDEX ix_admissions_bed_status ON admissions(bed_id, admission_status);
CREATE INDEX ix_beds_room_status ON beds(room_id, bed_status);
CREATE INDEX ix_history_bed_date ON bed_status_history(bed_id, changed_at);
CREATE INDEX ix_request_status ON admission_requests(department_id, request_status);
CREATE INDEX ix_alert_open ON capacity_alerts(department_id, alert_status);

-- A bed can have at most one currently admitted patient.
CREATE UNIQUE INDEX uq_active_admission_bed
    ON admissions (CASE WHEN admission_status = 'ADMITTED' THEN bed_id END);

CREATE OR REPLACE VIEW v_bed_summary AS
SELECT d.department_id,
       d.department_name,
       COUNT(b.bed_id) AS total_beds,
       SUM(CASE WHEN b.bed_status = 'AVAILABLE' THEN 1 ELSE 0 END) AS available_beds,
       SUM(CASE WHEN b.bed_status = 'OCCUPIED' THEN 1 ELSE 0 END) AS occupied_beds,
       SUM(CASE WHEN b.bed_status = 'CLEANING' THEN 1 ELSE 0 END) AS cleaning_beds,
       SUM(CASE WHEN b.bed_status = 'MAINTENANCE' THEN 1 ELSE 0 END) AS maintenance_beds,
       ROUND(100 * SUM(CASE WHEN b.bed_status = 'OCCUPIED' THEN 1 ELSE 0 END)
             / NULLIF(COUNT(b.bed_id), 0), 2) AS occupancy_pct,
       d.alert_threshold_pct
  FROM departments d
  LEFT JOIN rooms r ON r.department_id = d.department_id
  LEFT JOIN beds b ON b.room_id = r.room_id
 GROUP BY d.department_id, d.department_name, d.alert_threshold_pct;

CREATE OR REPLACE VIEW v_capacity_alerts AS
SELECT *
  FROM v_bed_summary
 WHERE occupancy_pct >= alert_threshold_pct;

-- This trigger records every bed-state change; it does not decide which changes are allowed.
CREATE OR REPLACE TRIGGER trg_bed_status_history
AFTER UPDATE OF bed_status ON beds
FOR EACH ROW
WHEN (OLD.bed_status <> NEW.bed_status)
BEGIN
    INSERT INTO bed_status_history (bed_id, old_status, new_status, change_reason)
    VALUES (:NEW.bed_id, :OLD.bed_status, :NEW.bed_status, 'Status changed through application workflow');
END;
/

-- Prevent direct assignment of a non-available bed in an admission row.
-- The package in 02_bed_management_package.sql will be the supported workflow.
CREATE OR REPLACE TRIGGER trg_validate_admission_bed
BEFORE INSERT OR UPDATE OF bed_id, admission_status ON admissions
FOR EACH ROW
DECLARE
    v_status beds.bed_status%TYPE;
BEGIN
    IF :NEW.admission_status = 'ADMITTED' THEN
        IF :NEW.bed_id IS NULL THEN
            RAISE_APPLICATION_ERROR(-20001, 'An ADMITTED patient must have a bed.');
        END IF;
        SELECT bed_status INTO v_status FROM beds WHERE bed_id = :NEW.bed_id;
        IF v_status <> 'AVAILABLE' THEN
            RAISE_APPLICATION_ERROR(-20002, 'The selected bed is not available.');
        END IF;
    END IF;
END;
/

COMMIT;
